function setDeadState(entry) {
  const currentHpInput = entry.querySelector(".enemy-current-hp");
  const nameSelect = entry.querySelector(".enemy-name");
  const hp = Number(currentHpInput.value);
  const isDead = Number.isFinite(hp) && hp === 0;

  entry.classList.toggle("is-dead", isDead);
  nameSelect.classList.toggle("is-dead", isDead);
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function inlineMarkdown(text) {
  let result = escapeHtml(text);
  result = result.replace(/`([^`]+)`/g, "<code>$1</code>");
  result = result.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  result = result.replace(/\*([^*]+)\*/g, "<em>$1</em>");
  return result;
}

function markdownToHtml(md) {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const out = [];
  let inList = false;
  let paragraph = [];

  const flushParagraph = () => {
    if (!paragraph.length) return;
    out.push("<p>" + paragraph.map(inlineMarkdown).join("<br>") + "</p>");
    paragraph = [];
  };

  const closeList = () => {
    if (!inList) return;
    out.push("</ul>");
    inList = false;
  };

  for (const raw of lines) {
    const line = raw.trimEnd();

    if (!line.trim()) {
      flushParagraph();
      closeList();
      continue;
    }

    if (line.startsWith("# ")) {
      flushParagraph();
      closeList();
      out.push("<h3>" + inlineMarkdown(line.slice(2).trim()) + "</h3>");
      continue;
    }

    if (line.startsWith("## ")) {
      flushParagraph();
      closeList();
      out.push("<h4>" + inlineMarkdown(line.slice(3).trim()) + "</h4>");
      continue;
    }

    if (/^\s*-\s+/.test(raw)) {
      flushParagraph();
      if (!inList) {
        out.push("<ul>");
        inList = true;
      }
      out.push("<li>" + inlineMarkdown(raw.replace(/^\s*-\s+/, "")) + "</li>");
      continue;
    }

    paragraph.push(line.trim());
  }

  flushParagraph();
  closeList();
  return out.join("");
}

async function getEnemyMarkdown(enemy) {
  if (!enemy.file) return "";

  try {
    const response = await fetch(enemy.file, { cache: "no-store" });
    if (!response.ok) throw new Error("Не удалось загрузить карточку");
    return await response.text();
  } catch (error) {
    return (window.ENEMY_MD_FALLBACK && window.ENEMY_MD_FALLBACK[enemy.file]) || "";
  }
}

async function renderEnemyDetails(entry) {
  const select = entry.querySelector(".enemy-name");
  const content = entry.querySelector(".enemy-details-content");
  const enemy = enemies[Number(select.value)];

  if (!enemy) return;

  content.innerHTML = '<p class="enemy-details-status">Загрузка…</p>';

  if (!enemy.file) {
    content.innerHTML = '<p class="enemy-details-status">Для этого врага подробное описание пока не добавлено.</p>';
    return;
  }

  const md = await getEnemyMarkdown(enemy);

  if (!md) {
    content.innerHTML = '<p class="enemy-details-status">Не удалось загрузить карточку врага.</p>';
    return;
  }

  content.innerHTML = markdownToHtml(md);
}

function applyEnemy(entry, enemyIndex) {
  const enemy = enemies[enemyIndex];
  if (!enemy) return;

  const currentHpInput = entry.querySelector(".enemy-current-hp");
  const totalHp = entry.querySelector(".enemy-total-hp");
  const details = entry.querySelector(".enemy-details");

  totalHp.textContent = String(enemy.maxHp);
  currentHpInput.value = String(enemy.maxHp);
  currentHpInput.max = String(enemy.maxHp);
  setDeadState(entry);

  if (!details.hidden) {
    renderEnemyDetails(entry);
  }
}

function createEnemyRow(initialEnemyIndex = 0, initialHp = null, insertAfterEntry = null) {
  if (!enemies.length) return null;

  const safeEnemyIndex = Number.isInteger(initialEnemyIndex)
    && initialEnemyIndex >= 0
    && initialEnemyIndex < enemies.length
      ? initialEnemyIndex
      : 0;

  const fragment = rowTemplate.content.cloneNode(true);
  const entry = fragment.querySelector(".enemy-entry");
  const nameSelect = entry.querySelector(".enemy-name");
  const currentHpInput = entry.querySelector(".enemy-current-hp");
  const expandButton = entry.querySelector(".enemy-expand");
  const duplicateButton = entry.querySelector(".enemy-duplicate");
  const deleteButton = entry.querySelector(".enemy-delete");
  const details = entry.querySelector(".enemy-details");

  enemies.forEach((enemy, index) => {
    const option = document.createElement("option");
    option.value = String(index);
    option.textContent = enemy.name;
    nameSelect.appendChild(option);
  });

  nameSelect.value = String(safeEnemyIndex);

  nameSelect.addEventListener("change", () => {
    applyEnemy(entry, Number(nameSelect.value));
  });

  currentHpInput.addEventListener("input", () => {
    if (currentHpInput.value === "") {
      entry.classList.remove("is-dead");
      nameSelect.classList.remove("is-dead");
      return;
    }

    let hp = Number(currentHpInput.value);
    const maxHp = Number(currentHpInput.max);

    if (!Number.isFinite(hp)) return;
    if (hp < 0) hp = 0;
    if (Number.isFinite(maxHp) && hp > maxHp) hp = maxHp;

    if (String(hp) !== currentHpInput.value) {
      currentHpInput.value = String(hp);
    }

    setDeadState(entry);
  });

  expandButton.addEventListener("click", async () => {
    const willOpen = details.hidden;
    details.hidden = !willOpen;
    expandButton.setAttribute("aria-expanded", String(willOpen));
    expandButton.setAttribute("aria-label", willOpen ? "Свернуть" : "Расширить");
    expandButton.title = willOpen ? "Свернуть" : "Расширить";

    if (willOpen) {
      await renderEnemyDetails(entry);
    }
  });

  duplicateButton.addEventListener("click", () => {
    createEnemyRow(
      Number(nameSelect.value),
      currentHpInput.value,
      entry
    );
  });

  deleteButton.addEventListener("click", () => {
    entry.remove();
    updateEmptyState();
  });

  if (insertAfterEntry && insertAfterEntry.parentElement === enemyList) {
    insertAfterEntry.after(fragment);
  } else {
    enemyList.appendChild(fragment);
  }

  applyEnemy(entry, safeEnemyIndex);

  if (initialHp !== null && initialHp !== "") {
    let hp = Number(initialHp);
    const maxHp = Number(currentHpInput.max);

    if (Number.isFinite(hp)) {
      hp = Math.max(0, hp);
      if (Number.isFinite(maxHp)) hp = Math.min(maxHp, hp);
      currentHpInput.value = String(hp);
      setDeadState(entry);
    }
  }

  updateEmptyState();
  return entry;
}

addEnemyButton.addEventListener("click", () => createEnemyRow());

