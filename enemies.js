let enemies = [];

function parseEnemiesCsv(text) {
  const lines = text
    .replace(/^\uFEFF/, "")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);

  if (lines.length < 2) return [];

  return lines.slice(1).map((line) => {
    const parts = line.split(";");
    const name = (parts[0] || "").trim();
    const maxHp = Number((parts[1] || "").trim());
    const file = (parts[2] || "").trim();

    if (!name || !Number.isFinite(maxHp) || maxHp < 0) return null;
    return { name, maxHp, file };
  }).filter(Boolean);
}

async function loadEnemies() {
  try {
    const response = await fetch("enemies.csv", { cache: "no-store" });
    if (!response.ok) throw new Error("Не удалось загрузить enemies.csv");
    enemies = parseEnemiesCsv(await response.text());
  } catch (error) {
    enemies = parseEnemiesCsv(FALLBACK_ENEMIES_CSV);
  }

  if (!enemies.length) {
    enemiesError.textContent = "В enemies.csv нет доступных врагов.";
    addEnemyButton.disabled = true;
  }
}

